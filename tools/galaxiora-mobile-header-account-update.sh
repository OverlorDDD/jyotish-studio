#!/usr/bin/env bash
# Galaxiora web-only responsive header / account dialog release.
# No Prisma migrations, no API restart, no environment variable edits.
set -Eeuo pipefail
umask 077
TARGET="${1:-}"
APP=/opt/galaxiora/app
BRANCH=fix/mobile-header-account-dialog-20261101
STATE="$HOME/galaxiora-mobile-auth-hotfix"
[[ "$TARGET" =~ ^[a-f0-9]{40}$ ]] || { echo 'STOP: provide exact 40-character green CI commit SHA'; exit 2; }
mkdir -p "$STATE"; chmod 700 "$STATE"
cd "$APP"
PREVIOUS=$(git rev-parse HEAD)
echo '=== GALAXIORA MOBILE HEADER + ACCOUNT DIALOG ==='
echo "previous=$PREVIOUS target=$TARGET"
for service in galaxiora-api.service galaxiora-web.service caddy.service; do
 systemctl is-active --quiet "$service" || { echo "STOP: $service inactive"; exit 1; }
done
curl -fsS --max-time 12 http://127.0.0.1:3000/uk >/dev/null
curl -fsS --max-time 12 http://127.0.0.1:4000/api/health >/dev/null
test -f .env || { echo 'STOP: missing production .env'; exit 1; }
git fetch origin "$BRANCH"
test "$(git rev-parse FETCH_HEAD)" = "$TARGET" || { echo 'STOP: target branch moved'; exit 1; }
git merge-base --is-ancestor "$PREVIOUS" "$TARGET" || { echo 'STOP: unexpected Git ancestry; do not force deployment'; exit 1; }
# Do not overwrite any human edits. next-env.d.ts is generated by Next.js.
while IFS= read -r filename; do
 case "$filename" in
  apps/web/next-env.d.ts|package.json) ;;
  *) echo "STOP: tracked local change must be reviewed: $filename"; exit 1 ;;
 esac
done < <(git diff --name-only HEAD)
cp -p .env "$STATE/env.backup"; chmod 600 "$STATE/env.backup"
echo "$PREVIOUS" > "$STATE/previous.sha"
rollback(){
 code=$?
 trap - EXIT
 if [ "$code" -eq 0 ]; then return; fi
 set +e
 echo 'MOBILE WEB HOTFIX FAILED — rebuilding previous web SHA'
 git stash push -m 'Galaxiora mobile rollback generated files' -- apps/web/next-env.d.ts package.json >/dev/null 2>&1 || true
 git switch --detach "$PREVIOUS"
 sudo systemctl stop galaxiora-web.service
 npm run build -w @jyotish/web
 sudo systemctl start galaxiora-web.service
 curl -fsS --max-time 15 http://127.0.0.1:3000/uk >/dev/null && echo 'RESTORED public web service'
 echo 'Database, API, Azure and .env were not modified.'
 exit "$code"
}
trap rollback EXIT
git stash push -m 'Galaxiora mobile generated files' -- apps/web/next-env.d.ts package.json >/dev/null 2>&1 || true
git switch --detach "$TARGET"
echo '=== STATIC WEB RESPONSIVENESS SAFETY CHECKS ==='
node --check e2e/mobile-header-account.spec.mjs
node --input-type=module <<'NODE'
import {readFileSync} from 'node:fs';
const account=readFileSync('apps/web/app/components/GlobalAccount.tsx','utf8');
const css=readFileSync('apps/web/app/globals.css','utf8');
if(!account.includes('createPortal(')||!account.includes('aria-modal="true"')||
 !css.includes('.as-account-overlay')||!css.includes('grid-template-columns:minmax(0,1fr) auto auto'))
 throw Error('Missing responsive account or safe header code');
console.log('PASS: portaled auth dialog and responsive header');
NODE
echo '=== BUILD WEB ONLY ==='
sudo systemctl stop galaxiora-web.service
npm run build -w @jyotish/web
sudo systemctl start galaxiora-web.service
ready=0
for attempt in $(seq 1 45); do
 status=$(curl -s -o /dev/null -w '%{http_code}' --max-time 4 http://127.0.0.1:3000/uk || true)
 if [ "$status" = 200 ] && systemctl is-active --quiet galaxiora-web.service; then ready=1; break; fi
 sleep 2
done
test "$ready" = 1 || { echo 'STOP: Web health check failed'; exit 1; }
for path in /uk /en /uk/news /uk/account; do
 curl -fsS --max-time 15 "http://127.0.0.1:3000$path" >/dev/null
done
curl -fsS --max-time 12 http://127.0.0.1:4000/api/health >/dev/null
trap - EXIT
echo '=== MOBILE ACCOUNT WEB RELEASE SUCCESS ==='
echo "Deployed $(git rev-parse HEAD)"
echo 'No changes to backend, PostgreSQL, credentials, News NMT or .env.'
