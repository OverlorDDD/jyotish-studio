#!/usr/bin/env node
/**
 * Run authentic JHoraKit -> JHora 8.0 Win32 extraction in an isolated Wine/Xvfb runner.
 * Every input is synthetic and deterministic. Fail CLOSED on first missing export.
 * No natal user data, browser interaction or cloud AI.
 */
import {spawnSync} from 'node:child_process';
import {readFileSync,writeFileSync,existsSync,statSync,readdirSync} from 'node:fs';
import {join,resolve,relative} from 'node:path';
import {createHash} from 'node:crypto';
import {VARGA_PROFILE} from '../packages/jyotish-core/src/vargas.ts';
const home=resolve(process.env.N4_JHORA_EXPORT_ROOT||'');
const kit=resolve(process.env.JHORA_KIT_ROOT||'');
const settings=resolve(process.env.N4_JHORA_INI||'');
if(!home||!kit||!settings||!existsSync(settings))
 throw Error('JHora8 exports root, pinned kit and JHora INI are mandatory');
const ini=readFileSync(settings,'utf8');
const wanted={
 HoraPreference:'0',D3Preference:'0',D4Preference:'0',D7Preference:'0',
 D9Preference:'0',D10Preference:'0',D12Preference:'0',D16Preference:'0',
 D20Preference:'0',D24Preference:'0',D27Preference:'0',D30Preference:'0',
 D60Preference:'0',DivLongFromEndToo:'0',
 Siddhanta:'0',TopocentricPositions:'0',TruePositions:'1'
};
const actual=Object.fromEntries([...ini.matchAll(/^([A-Za-z0-9_]+)=([^\r\n]+)/gm)].map(x=>[x[1],x[2].trim()]));
for(const [k,v] of Object.entries(wanted)){
 if(actual[k]!==v)throw Error('Refusing JHora with unpinned method '+k+': '+actual[k]+' rather than '+v);
}
const iniSha=createHash('sha256').update(ini).digest('hex');
const limit=Number(process.env.N4_JHORA_LIMIT||50);
if(!Number.isInteger(limit)||limit<1||limit>50)throw Error('Invalid N4 limit');
const cases=[];
for(let i=0;i<limit;i++){
 const id='N4-SYNTH-'+String(i+1).padStart(3,'0');
 const year=1990+(i%30),month=1+(i%12),day=5+(i%20);
 const date=[year,String(month).padStart(2,'0'),String(day).padStart(2,'0')].join('-');
 const hour=(i*7+5)%24,minute=(i*13+11)%60;
 const time=String(hour).padStart(2,'0')+':'+String(minute).padStart(2,'0');
 const lat=Number((-48+i*1.91).toFixed(4)),lon=Number((-150+i*6.07).toFixed(4));
 const tz=(i%19)-9;
 // JHora rewrites jhora.ini after each session; restore pinned profile for every case.
 writeFileSync(settings,ini);
 const args=['run','--package-path',kit,'jhora-extract',
  '--name',id,'--date',date,'--time',time,
  '--lat',String(lat),'--lon',String(lon),'--tz',String(tz),
  '--place','Synthetic Reference City'];
 console.log('N4_JHORA8_CAPTURE '+(i+1)+'/'+limit+' '+id);
 const started=Date.now();
 const cmd=spawnSync('swift',args,{
  encoding:'utf8',timeout:150000,env:{...process.env,JHORA_OUT_DIR:home},
  maxBuffer:3*1024*1024
 });
 if(cmd.status!==0||cmd.error){
  console.error((cmd.stderr||'').slice(-4000));
  throw Error('Authentic JHora8 export failed for '+id+': '+String(cmd.error||cmd.status));
 }
 const folder=join(home,id);
 if(!existsSync(folder))throw Error('JHoraKit output folder absent: '+id);
 const candidates=readdirSync(folder).map(n=>join(folder,n,'chart.json'))
   .filter(p=>existsSync(p)&&statSync(p).size>1000)
   .sort((a,b)=>statSync(b).mtimeMs-statSync(a).mtimeMs);
 if(candidates.length===0)throw Error('No complete JHoraKit chart.json for '+id);
 const selected=candidates[0];
 const parsed=JSON.parse(readFileSync(selected,'utf8'));
 if(parsed?.meta?.name!==id||Object.keys(parsed.divisionals||{}).length<16)
  throw Error('Incomplete/wrong original JHora chart.json for '+id);
 cases.push({id,synthetic:true,export:relative(home,selected)});
 console.log('N4_CAPTURE_OK '+id+' '+(Date.now()-started)+'ms');
}
if(cases.length!==50)throw Error('Only '+cases.length+' authentic JHora8 cases captured; full certification requires 50');
const manifest={
 profile:VARGA_PROFILE,
 source:'Original Jagannatha Hora 8.0 via JHoraKit raw clipboard extracts',
 sourceVersion:'8.0.0.0',
 referenceSettings:'Authentic JHora 8.0 pinned INI SHA256 '+iniSha+'; '+
  Object.entries(wanted).map(([k,v])=>k+'='+v).join('; ')+
  '; reference corpus generated by pinned JHoraKit (original binary via Wine)',
 cases
};
writeFileSync(join(home,'n4-manifest.json'),JSON.stringify(manifest,null,2)+'\n',{flag:'wx',mode:0o600});
console.log('N4_JHORA8_50_ORIGINAL_EXPORTS_CREATED; ini_sha256='+iniSha);
