"""Historical three-case Swiss synthetic fixture adapter. Explicit MOSEPH mode.
Never imported by Galaxiora runtime. Unlike precise natal/transit adapters,
this intentionally reproduces OLD fixtures generated by Moshier fallback.
"""
import json,sys
from datetime import datetime,timezone
import swisseph as swe
def main():
 data=json.load(sys.stdin)
 dt=datetime.fromisoformat(data['utc'].replace('Z','+00:00')).astimezone(timezone.utc)
 hour=dt.hour+dt.minute/60+dt.second/3600
 jd=swe.julday(dt.year,dt.month,dt.day,hour)
 swe.set_sid_mode(swe.SIDM_LAHIRI)
 flag=swe.FLG_MOSEPH|swe.FLG_SPEED|swe.FLG_SIDEREAL
 ay=swe.get_ayanamsa_ex_ut(jd,swe.FLG_MOSEPH)[1]
 mean=swe.get_ayanamsa_ex_ut(jd,swe.FLG_MOSEPH|swe.FLG_NONUT)[1]
 asc=(swe.houses(jd,data['latitude'],data['longitude'],b'P')[1][0]-mean)%360
 bodies=[('Sun',swe.SUN),('Moon',swe.MOON),('Mars',swe.MARS),
  ('Mercury',swe.MERCURY),('Jupiter',swe.JUPITER),('Venus',swe.VENUS),
  ('Saturn',swe.SATURN),('Rahu',swe.MEAN_NODE)]
 positions=[]
 for name,body in bodies:
  val,ret=swe.calc_ut(jd,body,flag)
  if (ret&7)!=swe.FLG_MOSEPH:raise RuntimeError('Historical fixture unexpectedly switched backend: '+name)
  positions.append(dict(name=name,longitude=val[0]%360,speed=val[3]))
 rahu=positions[-1]
 positions.append(dict(name='Ketu',longitude=(rahu['longitude']+180)%360,speed=rahu['speed']))
 print(json.dumps({'ayanamsa':ay,'ascendant':asc,'positions':positions,
  'julianDay':jd,'backend':'EXPLICIT_MOSHIER_LEGACY_SYNTHETIC_FIXTURE_NOT_FOR_PRODUCTION'}))
if __name__=='__main__':main()
