import {fixtureAccount} from './support/disposable-accounts.mjs';
import {test,expect} from '@playwright/test';
import {randomUUID} from 'node:crypto';
const credentials=()=>({email:'galaxicom-c2-'+randomUUID().slice(0,12)+'@example.invalid',
 password:'GalaxiCom-C2-valid-password-2026'});
test('GalaxiCom C2: long writing, full-width edit, revisions, follows, votes, notifications and quick delete',async({page})=>{
 test.setTimeout(120000);
 if(!process.env.DATABASE_URL)test.skip();
 const {PrismaClient}=await import('@prisma/client');
 const db=new PrismaClient();
 const a=credentials(),b=credentials();let aid='',bid='',tid='',pid='';
 const url=(p)=>'/api/v1/com/'+p;
 try{
  expect((await page.request.get(url('notifications'))).status()).toBe(401);
  const joinA=await fixtureAccount(page,{data:a});
  expect(joinA.status()).toBe(201);aid=(await joinA.json()).user.id;
  const original='Натальна карта Джйотіш та взаємодія між D1 і Навамшею';
  const longBody=('Розглядаю положення грах в різних варгах та порівнюю їх із класичними текстами. ').repeat(88);
  expect(original.length).toBeLessThanOrEqual(160);
  expect(longBody.length).toBeLessThanOrEqual(8000);
  // Shorter than old minimum now allowed; original safety maxima restored.
  const oneChar=await page.request.post(url('threads'),{data:{categorySlug:'jyotish',title:'?',body:'!'}});
  expect(oneChar.status()).toBe(201);
  await db.comThread.delete({where:{id:(await oneChar.json()).id}});
  expect((await page.request.post(url('threads'),{data:{categorySlug:'jyotish',title:'X'.repeat(161),body:'a'}})).status()).toBe(400);
  expect((await page.request.post(url('threads'),{data:{categorySlug:'jyotish',title:'Valid',body:'a'.repeat(8001)}})).status()).toBe(400);
  const created=await page.request.post(url('threads'),{data:{categorySlug:'jyotish',title:original,body:longBody}});
  expect(created.status()).toBe(201);tid=(await created.json()).id;
  const suggestions=await (await page.request.get(url('duplicates?title='+encodeURIComponent(original.slice(0,200))))).json();
  expect(suggestions.items.some(t=>t.id===tid)).toBe(true);
  await page.goto('/uk/community/topic/'+tid);
  await expect(page.getByTestId('com-thread')).toBeVisible();
  const editorButton=page.getByTestId('com-thread').getByRole('button',{name:'Редагувати'});
  await editorButton.click();
  const editor=page.getByTestId('com-fullwidth-editor');
  await expect(editor).toBeVisible();
  const parent=await page.getByTestId('com-thread').boundingBox();
  const frame=await editor.boundingBox();
  const area=await editor.locator('textarea').boundingBox();
  expect(parent&&frame&&area).toBeTruthy();
  expect(frame.width).toBeGreaterThan(parent.width*0.70);
  expect(area.height).toBeGreaterThan(260);
  await editor.locator('input').fill('Оновлена велика тема Джйотіш: огляд Навамші');
  await editor.locator('textarea').fill(longBody+' Оновлення містить ще кілька спостережень.');
  await editor.getByRole('button',{name:'Зберегти'}).click();
  await expect(page.getByText('Оновлена велика тема Джйотіш: огляд Навамші')).toBeVisible();
  const revisions=await (await page.request.get(url('threads/'+tid+'/revisions'))).json();
  expect(revisions.items[0].title).toBe(original.trim());
  expect(revisions.items[0].body).toBe(longBody.trim());
  const joinedB=await fixtureAccount(page,{data:b});
  expect(joinedB.status()).toBe(201);bid=(await joinedB.json()).user.id;
  expect((await page.request.get(url('threads/'+tid+'/revisions'))).status()).toBe(404);
  const watch=await page.request.put(url('threads/'+tid+'/follow'));
  expect(watch.status()).toBe(200);
  const replyBody='Відповідь із детальним аналізом '+('системи домів і накшатр '.repeat(195));
  expect(replyBody.length).toBeLessThanOrEqual(5000);
  expect((await page.request.post(url('threads/'+tid+'/posts'),{data:{body:'x'.repeat(5001)}})).status()).toBe(400);
  const reply=await page.request.post(url('threads/'+tid+'/posts'),{data:{body:replyBody}});
  expect(reply.status()).toBe(201);pid=(await reply.json()).id;
  expect((await page.request.post(url('threads/'+tid+'/posts'),{data:{body:replyBody}})).status()).toBe(409);
  expect((await page.request.put(url('posts/'+pid+'/helpful'))).status()).toBe(200);
  expect((await page.request.put(url('posts/'+pid+'/helpful'))).status()).toBe(200);
  const act1=await (await page.request.get(url('threads/'+tid+'/activity'))).json();
  expect(act1.likes[pid].count).toBe(1);
  expect(act1.following).toBe(true);
  expect((await page.request.delete(url('posts/'+pid+'/helpful'))).status()).toBe(200);
  expect((await (await page.request.get(url('threads/'+tid+'/activity'))).json()).likes[pid]).toBeUndefined();
  const profile=await (await page.request.get(url('profiles/'+bid))).json();
  expect(profile.replyCount).toBe(1);
  expect(JSON.stringify(profile)).not.toContain(b.email);
  expect((await page.request.get(url('notifications'))).status()).toBe(200);
  // Reply author is never notified of their own message.
  expect((await (await page.request.get(url('notifications'))).json()).unread).toBe(0);
  const loginA=await page.request.post('/api/v1/account/login',{data:a});
  expect(loginA.status()).toBe(201);
  const inbox=await (await page.request.get(url('notifications'))).json();
  expect(inbox.unread).toBe(1);
  expect(inbox.items[0].threadId).toBe(tid);
  const nId=inbox.items[0].id;
  expect((await page.request.patch(url('notifications/'+nId+'/read'))).status()).toBe(200);
  expect((await (await page.request.get(url('notifications'))).json()).unread).toBe(0);
  expect((await page.request.put(url('posts/'+pid+'/helpful'))).status()).toBe(200);
  const votes=await (await page.request.get(url('threads/'+tid+'/activity'))).json();
  expect(votes.likes[pid].count).toBe(1);
  expect(votes.myLikes).toContain(pid);
  const loginB=await page.request.post('/api/v1/account/login',{data:b});
  expect(loginB.status()).toBe(201);
  await db.user.update({where:{id:bid},data:{role:'SUPPORT'}});
  const quick=await page.request.delete(url('mod/threads/'+tid));
  expect(quick.status()).toBe(200);
  expect((await page.request.get(url('threads/'+tid))).status()).toBe(404);
  expect((await page.request.get(url('threads/'+tid+'/activity'))).status()).toBe(404);
  const log=await db.comModerationAction.findMany({where:{targetId:tid,action:'DELETE'}});
  expect(log.length).toBe(1);
  expect(log[0].actorId).toBe(bid);
  expect((await (await page.request.get(url('notifications'))).json()).items).toEqual([]);
 }finally{
  if(tid)await db.comThread.deleteMany({where:{id:tid}});
  if(tid)await db.comModerationAction.deleteMany({where:{targetId:tid}});
  if(aid||bid)await db.user.deleteMany({where:{id:{in:[aid,bid]}}});
  await db.$disconnect();
 }
});
